// Логика демо-помощника заявок. Чистые функции без DOM: проверяются тестами в Node.
// Демо работает на правилах (ключевые слова), без ИИ. В боевой версии вместо правил отвечает языковая модель,
// а заявка уходит менеджеру в Telegram. Ничего не отправляется и не сохраняется.
(function (root) {
  var FAQ = [
    {
      id: "price",
      re: /сколько|цен[аы]|стоим|прайс|₽|руб|дорог|тариф/i,
      text: "В демо цены условные: выходные (2 дня) от 6 900 ₽, классика (3 дня) от 11 900 ₽, длинный выход (5 дней) от 21 900 ₽. Бронь подтверждается предоплатой, остаток вносится перед выходом.",
    },
    {
      id: "dates",
      re: /дат[аыу]|когда|ближайш|сезон|расписан|график/i,
      text: "Выходы идут в тёплое время и зимой по прогнозу погоды. В демо даты условные: оставьте контакт, и менеджер пришлёт свободные выходы.",
    },
    {
      id: "bring",
      re: /взять|брать|вещи|одежд|обув|снаряж|рюкзак|список/i,
      text: "Нужны рюкзак, спальник, коврик, треккинговая обувь, дождевик и тёплый слой. Подробный список пришлём после записи, а часть снаряжения можно взять напрокат.",
    },
    {
      id: "route",
      re: /добрат|доехат|транспорт|встреч|вокзал|куда ехать|где начин/i,
      text: "Вход в парк находится примерно в 3 км от вокзала Златоуста. В день выхода мы встретим группу и организуем переезд до тропы.",
    },
    {
      id: "level",
      re: /сложн|подготов|опыт|новичк|начина|ребён|ребен|дет[иям]|пожил|возраст/i,
      text: "Для двух-трёх дней достаточно обычной формы и привычки ходить пешком. Тропа каменистая, подъём на Двуглавую идёт по лестнице. С детьми подойдёт спокойный маршрут по Долине сказок.",
    },
    {
      id: "weather",
      re: /погод|дожд|снег|холод|мороз|ветер|прогноз/i,
      text: "В горах погода меняется быстро. В плане всегда есть запасной день, а при штормовом предупреждении мы переносим выход без штрафа.",
    },
    {
      id: "safety",
      re: /безопас|опасн|страшно|аптечк|страхов|мчс/i,
      text: "Идём группой до 8 человек по тропам, темп задаёт самый медленный участник. У гида аптечка и план выхода, а при плохой погоде выход переносим.",
    },
    {
      id: "hello",
      re: /^(привет|здравств|добрый|хай|hello)/i,
      text: "Здравствуйте! Я помощник по заявкам. Могу рассказать про цены, даты, что взять с собой и записать вас на выход.",
    },
  ];

  var BOOK = /записат|забронир|оставить заявк|заявк[уаи]|хочу пойти|хочу на|свяжит|перезвон|менеджер|оператор|человек/i;

  function norm(s) {
    return String(s || "").trim().replace(/\s+/g, " ");
  }

  function newState() {
    return { step: "chat", lead: { name: "", contact: "", format: "", topics: [] } };
  }

  function validContact(s) {
    var t = norm(s);
    var digits = t.replace(/\D/g, "");
    return /^@[a-z0-9_]{4,32}$/i.test(t) || /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(t) || digits.length >= 10;
  }

  var FORMATS = ["Выходные (2 дня)", "Классика (3 дня)", "Длинный выход (5 дней)", "Пока не знаю"];

  /** Один шаг диалога: принимает состояние и текст клиента, возвращает ответы бота и новое состояние. */
  function step(state, input) {
    var s = JSON.parse(JSON.stringify(state || newState()));
    var text = norm(input);
    var out = [];
    if (!text) return { state: s, messages: [{ text: "Напишите вопрос или выберите вариант ниже." }] };

    if (s.step === "name") {
      if (text.length < 2 || text.length > 60) return { state: s, messages: [{ text: "Как к вам обращаться? Достаточно имени." }] };
      s.lead.name = text;
      s.step = "contact";
      return { state: s, messages: [{ text: "Приятно познакомиться, " + text + ". Оставьте Telegram (@имя), телефон или почту, чтобы менеджер мог ответить." }] };
    }
    if (s.step === "contact") {
      if (!validContact(text)) return { state: s, messages: [{ text: "Не получилось распознать контакт. Напишите @имя в Telegram, телефон с кодом или почту." }] };
      s.lead.contact = text;
      s.step = "format";
      return { state: s, messages: [{ text: "Какой формат интересует?", chips: FORMATS }] };
    }
    if (s.step === "format") {
      s.lead.format = text.slice(0, 60);
      s.step = "done";
      return {
        state: s,
        lead: s.lead,
        messages: [{ text: "Готово, заявка собрана. В боевой версии она сейчас ушла бы менеджеру в Telegram, а здесь это демо, и ничего не отправлено. Можете задать ещё вопросы." }],
      };
    }

    // свободный диалог (в том числе после заявки)
    if (BOOK.test(text)) {
      s.step = "name";
      return { state: s, messages: [{ text: "С удовольствием запишу. Как вас зовут?" }] };
    }
    var hit = FAQ.filter(function (f) {
      return f.re.test(text);
    });
    if (hit.length) {
      hit.slice(0, 2).forEach(function (h) {
        if (s.lead.topics.indexOf(h.id) < 0) s.lead.topics.push(h.id);
        out.push({ text: h.text });
      });
      out.push({ text: "Хотите, запишу вас на выход?", chips: ["Записаться", "Сколько стоит?", "Что взять?"] });
      return { state: s, messages: out };
    }
    return {
      state: s,
      messages: [{ text: "Не уверен, что понял вопрос, и не хочу выдумывать. Могу передать его менеджеру: оставьте контакт, и вам ответят.", chips: ["Записаться", "Сколько стоит?", "Как добраться?"] }],
    };
  }

  var api = { FAQ: FAQ, FORMATS: FORMATS, newState: newState, step: step, validContact: validContact };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.AssistantKB = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
